// 预编译小写关键词，便于英文匹配
const INDEX = BRANDS.map(b => ({ p: b.p, kws: b.kw.map(k => k.toLowerCase()) }));

function canonicalCompany(name) {
  if (!name) return '';
  const lower = String(name).toLowerCase();
  for (const b of INDEX) {
    for (const k of b.kws) {
      if (lower.includes(k)) return b.p;
    }
  }
  return String(name).trim();
}

